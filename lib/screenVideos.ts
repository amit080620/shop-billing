/** The video for this screen, if there is one: its chapter and the second to start from. */
export function videoForScreen(pathname: string, businessType: string): { id: string; t: number } | null {
  let best: string | null = null;
  for (const path of Object.keys(SCREENS)) {
    if ((pathname === path || pathname.startsWith(path + "/")) && (!best || path.length > best.length)) best = path;
  }
  if (!best) return null;
  const e = SCREENS[best];
  const [id, t] = e.byType?.[businessType] ?? e.at;
  return { id, t };
}
